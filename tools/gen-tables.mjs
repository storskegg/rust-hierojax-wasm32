#!/usr/bin/env node
// Generates the static tables of hieroxide-core from upstream's data files:
//
//   src/insertions.js            -> crates/hieroxide-core/src/tables/insertions.rs
//   src/ligatures.js             -> crates/hieroxide-core/src/tables/ligatures.rs
//   src/standardizedvariants.js  -> crates/hieroxide-core/src/tables/variants.rs
//
//   node tools/gen-tables.mjs            write the files
//   node tools/gen-tables.mjs --check    exit 1 if the committed files differ from what
//                                        upstream's data would generate
//
// The data files are evaluated as upstream loads them (they assign to a global `Shapes`),
// in a fresh vm context, and read only. Tables are plain sorted arrays for binary
// search. Anything the generator does not know how to emit (a key it has not seen, a
// non-character key) is an error, so a change upstream cannot slip through unnoticed.
//
// Order is kept where upstream's code depends on it: `LIGATURES` is in the order of
// `for (const ch in Shapes.ligatures)` (memoLigatures keeps the first match), and the
// alternatives of an insertion are in array order (the first that fits wins).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'crates/hieroxide-core/src/tables');

const Shapes = {};
const ctx = vm.createContext({ Shapes });
for (const f of ['insertions', 'ligatures', 'standardizedvariants']) {
  vm.runInContext(fs.readFileSync(path.join(SRC, f + '.js'), 'utf8'), ctx, { filename: f + '.js' });
}

const fail = (m) => {
  throw new Error('gen-tables: ' + m);
};
const cp = (s) => {
  const a = [...s];
  if (a.length !== 1) fail(`expected one character, got ${JSON.stringify(s)}`);
  return a[0].codePointAt(0);
};
const chr = (s) => `'\\u{${cp(s).toString(16).toUpperCase()}}'`;
const num = (n) => {
  if (typeof n !== 'number' || !Number.isFinite(n)) fail(`not a finite number: ${n}`);
  const s = String(n);
  return /^-?\d+$/.test(s) ? s + '.0' : s;
};
const cmpCp = (a, b) => cp(a) - cp(b);
const only = (obj, allowed, what) => {
  for (const k of Object.keys(obj)) if (!allowed.includes(k)) fail(`${what}: unknown key ${JSON.stringify(k)}`);
};

const HEADER = (name) =>
  `// @generated by tools/gen-tables.mjs from src/${name}. Do not edit; run\n` +
  `// \`node tools/gen-tables.mjs\` to regenerate (\`--check\` verifies).\n\n`;

const PLACES = ['ts', 'bs', 'te', 'be', 'm', 't', 'b'];

function genInsertions() {
  const rows = [];
  // Most alternatives use a few of the same adjustments: each is written once, and an alternative
  // has an index per place. 0 is an absent place.
  const adjs = ['None'];
  const adjIndex = (s) => {
    let i = adjs.indexOf(s);
    if (i < 0) i = adjs.push(s) - 1;
    if (i > 255) fail('too many distinct adjustments for u8');
    return i;
  };
  for (const ch of Object.keys(Shapes.insertions).sort(cmpCp)) {
    const alts = Shapes.insertions[ch];
    if (!Array.isArray(alts)) fail('insertion entry is not an array');
    const items = alts.map((alt) => {
      only(alt, ['glyph', 'rot', 'out', ...PLACES], `insertion ${chr(ch)}`);
      const glyph = 'glyph' in alt ? `Some(${chr(alt.glyph)})` : 'None';
      const rot = 'rot' in alt ? alt.rot : 0;
      if (!Number.isInteger(rot) || rot < 0 || rot > 359) fail('bad rot');
      const places = PLACES.map((p) => {
        if (!(p in alt)) return 0;
        const a = alt[p];
        only(a, ['x', 'y'], `adjustment ${p} of ${chr(ch)}`);
        const x = 'x' in a ? `Some(${num(a.x)})` : 'None';
        const y = 'y' in a ? `Some(${num(a.y)})` : 'None';
        return adjIndex(`Some(Adj { x: ${x}, y: ${y} })`);
      });
      return `Alt { glyph: ${glyph}, rot: ${rot}, places: [${places.join(', ')}] }`;
    });
    rows.push(`    (${chr(ch)}, &[\n        ${items.join(',\n        ')},\n    ]),`);
  }
  const set = (s, name) => {
    const cs = [...s].sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
    return `pub static ${name}: &[char] = &[${cs.map(chr).join(', ')}];\n`;
  };
  return (
    HEADER('insertions.js') +
    `use super::{Adj, Alt};\n\n` +
    `/// \`Shapes.insertions\`: for each character, its alternatives in upstream's order.\n` +
    `/// Sorted by character, for binary search.\n` +
    `pub static INSERTIONS: &[(char, &[Alt])] = &[\n${rows.join('\n')}\n];\n\n` +
    `/// What \`Alt::places\` index.\n` +
    `pub static ADJS: &[Option<Adj>] = &[\n    ${adjs.join(',\n    ')},\n];\n\n` +
    `/// \`Shapes.topupChars\`, sorted.\n` +
    set(Shapes.topupChars, 'TOPUP_CHARS') +
    `\n/// \`Shapes.bottomdownChars\`, sorted.\n` +
    set(Shapes.bottomdownChars, 'BOTTOMDOWN_CHARS')
  );
}

function genLigatures() {
  const names = Object.keys(Shapes.ligatures); // for..in order
  const sign = (s) => {
    only(s, ['ch', 'x', 'y', 'w', 'h', 'mirror'], 'ligature sign');
    return `Sign { ch: ${chr(s.ch)}, x: ${num(s.x)}, y: ${num(s.y)}, w: ${num(s.w)}, h: ${num(s.h)}, mirror: ${s.mirror ? 'true' : 'false'} }`;
  };
  const list = (a) => (a ? `&[${a.map(sign).join(', ')}]` : '&[]');
  const rows = names.map((ch) => {
    const l = Shapes.ligatures[ch];
    only(l, ['type', 'alt', 'groups', 'horizontal', 'vertical'], `ligature ${chr(ch)}`);
    const kind = { overlay: 'Overlay', vertical: 'Vertical', horizontal: 'Horizontal' }[l.type] ?? fail('ligature type ' + l.type);
    if ('alt' in l && l.alt !== true) fail('alt is not true');
    return (
      `    Ligature { ch: ${chr(ch)}, kind: LigKind::${kind}, alt: ${'alt' in l ? 'true' : 'false'},\n` +
      `        groups: ${list(l.groups)},\n        horizontal: ${list(l.horizontal)},\n        vertical: ${list(l.vertical)} },`
    );
  });
  const index = names
    .map((ch, i) => [cp(ch), ch, i])
    .sort((a, b) => a[0] - b[0])
    .map(([, ch, i]) => `(${chr(ch)}, ${i})`);
  return (
    HEADER('ligatures.js') +
    `use super::{LigKind, Ligature, Sign};\n\n` +
    `/// \`Shapes.ligatures\` in upstream's \`for (const ch in ...)\` order.\n` +
    `pub static LIGATURES: &[Ligature] = &[\n${rows.join('\n')}\n];\n\n` +
    `/// Character to position in [\`LIGATURES\`], sorted by character.\n` +
    `pub static LIGATURE_INDEX: &[(char, u16)] = &[${index.join(', ')}];\n`
  );
}

function genVariants() {
  const chars = Object.keys(Shapes.rotations).sort(cmpCp);
  const rows = chars.map((ch) => {
    const r = Shapes.rotations[ch];
    // Object.keys on integer-like keys is ascending numeric order, as upstream sees it.
    const items = Object.keys(r).map((k) => {
      const rot = Number(k);
      if (!Number.isInteger(rot) || String(rot) !== k) fail('bad rotation key ' + k);
      if (!Number.isInteger(r[k])) fail('bad rotation adjustment');
      return `(${rot}, ${r[k]})`;
    });
    return `    (${chr(ch)}, &[${items.join(', ')}]),`;
  });
  return (
    HEADER('standardizedvariants.js') +
    `/// \`Shapes.rotations\`: for each character, (coarse rotation, adjustment in degrees) in\n` +
    `/// the order of \`Object.keys\`. Sorted by character, for binary search.\n` +
    `pub static ROTATIONS: &[(char, &[(u16, i16)])] = &[\n${rows.join('\n')}\n];\n`
  );
}

const files = {
  'insertions.rs': genInsertions(),
  'ligatures.rs': genLigatures(),
  'variants.rs': genVariants(),
};

const check = process.argv.includes('--check');
let bad = 0;
for (const [name, text] of Object.entries(files)) {
  const file = path.join(OUT, name);
  if (check) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have !== text) {
      console.error(`${path.relative(ROOT, file)} is out of date`);
      bad++;
    }
  } else {
    fs.mkdirSync(OUT, { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${path.relative(ROOT, file)} (${text.length} bytes)`);
  }
}
if (check) {
  if (bad) process.exit(1);
  console.log('tables are current');
}
