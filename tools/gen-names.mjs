// Writes crates/hieroxide-cli/src/names.rs: the Gardiner name of each hieroglyph code point, from the tables of
// hieroxide-tables, for the CLI's warning about signs the font lacks. Run: node tools/gen-names.mjs
import fs from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const byChar = new Map();
for (const file of ['unipoints.rs', 'extpoints.rs']) {
  const src = fs.readFileSync(`${root}hieroxide-tables/src/${file}`, 'utf8');
  for (const m of src.matchAll(/"([A-Za-z0-9]+)"\s*=>\s*'\\u\{([0-9A-Fa-f]+)\}'/g)) {
    const cp = parseInt(m[2], 16);
    if (!byChar.has(cp)) byChar.set(cp, m[1]);
  }
}
const rows = [...byChar].sort((a, b) => a[0] - b[0]);
let out = '// SPDX-License-Identifier: GPL-3.0-only\n// Generated by tools/gen-names.mjs from hieroxide-tables: do not edit.\n\n';
out += '/// Code point and Gardiner name, sorted by code point.\nstatic NAMES: [(u32, &str); ' + rows.length + '] = [\n';
for (const [cp, name] of rows) out += `    (0x${cp.toString(16).toUpperCase()}, "${name}"),\n`;
out += '];\n\n/// The Gardiner name of a sign, if the tables have one.\npub fn gardiner(ch: char) -> Option<&\'static str> {\n    let i = NAMES.binary_search_by_key(&(ch as u32), |e| e.0).ok()?;\n    Some(NAMES[i].1)\n}\n';
fs.writeFileSync(`${root}crates/hieroxide-cli/src/names.rs`, out);
console.log(`${rows.length} names`);
